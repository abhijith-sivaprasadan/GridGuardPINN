"""Reproduce source comparisons and the approximate balanced-fault experiment."""

import argparse
import csv
import json
import platform
from pathlib import Path

import numpy as np
import scipy

from gridguardpinn.ssr_estimator import FBM, shaft_modes, shaft_ringdown
from gridguardpinn.ssr_estimator import parameters as p
from gridguardpinn.ssr_estimator.estimation import compare_modes, matrix_pencil, welch_modes


def analyse(signal, sample_rate, reference_decay=None, poles=12):
    pencil = matrix_pencil(signal, sample_rate, poles=poles)
    spectral, diagnostic = welch_modes(signal, sample_rate)
    result = {}
    for name, modes in [("matrix_pencil", pencil), ("welch", spectral)]:
        rows, unmatched = compare_modes(modes, p.PUBLISHED_HZ, reference_decay)
        result[name] = {"comparison": rows, "unmatched_estimates": unmatched}
    result["welch_diagnostics"] = diagnostic
    return result


def run(output, include_fault=True):
    output.mkdir(parents=True, exist_ok=True)
    result = {
        "scope": "Published mechanical reference comparison plus custom FBM transient circuit "
                 "with approximate balanced Thevenin fault. No field validation.",
        "source_doi": "10.1109/T-PAS.1977.32485",
        "environment": {"python": platform.python_version(), "numpy": np.__version__,
                        "scipy": scipy.__version__, "platform": platform.platform()},
        "shaft_computed_frequencies_hz": shaft_modes()[0].tolist(),
        "fifth_mode_reference": "unverified: not tabulated in the primary source",
        "published_amplitude_reference": "unavailable",
        "protocol": {"sample_rate_hz": 240, "shaft_duration_s": 12,
                     "fault_duration_s": p.FAULT_DURATION, "fault_start_s": 0.5,
                     "match_tolerance_hz": 0.5, "pencil_shaft_poles": 12,
                     "pencil_fault_poles": 20, "welch_prominence_fraction": 0.01},
    }
    for label, damped in [("shaft_no_load", True), ("shaft_transient_undamped", False)]:
        _, speed = shaft_ringdown(no_load_damping=damped)
        reference = p.NO_LOAD_DECREMENT if damped else np.zeros(4)
        result[label] = analyse(speed[:, 4], 240, reference)
    if include_fault:
        model = FBM()
        result["electrical_resonance"] = {
            "published_approximate_hz": 40.0,
            "intact_frozen_shaft_hz": model.frozen_electrical_resonance(),
            "fault_thevenin_frozen_shaft_hz": model.frozen_electrical_resonance(fault=True),
            "interpretation": "60 minus the low-frequency rotating-frame circuit pole; "
                              "approximate source statement, not an exact target or coupled mode",
        }
        simulation = model.simulate()
        columns = np.column_stack([simulation.time, simulation.speed_pu,
                                   simulation.electrical_torque_pu, simulation.voltage_pu,
                                   simulation.frequency_hz])
        with (output / "fault_signals.csv").open("w", newline="", encoding="utf-8") as stream:
            writer = csv.writer(stream)
            writer.writerow(["time_s"] + [f"speed_{mass}_pu" for mass in p.MASSES]
                            + ["electrical_torque_pu", "terminal_voltage_pu",
                               "terminal_frequency_hz"])
            writer.writerows(columns)
        window = (simulation.time >= 1.0) & (simulation.time <= 2.75)
        result["fault"] = {
            "equilibrium_residual": simulation.equilibrium_residual,
            "window_s": [1.0, 2.75],
            "duration_s": 3.0,
            "max_speed_deviation_pu": float(np.max(abs(simulation.speed_pu - 1))),
            "validity_note": "Ideal elastic shaft, zero mechanical damping, no protection "
                             "or material limits. Large excursions are not plant predictions.",
            "reference_warning": "Published bare-shaft frequencies are proximity references, "
                                 "not ground truth for coupled nonlinear fault modes. Published "
                                 "no-load decrement is NOT the coupled-system decay.",
            "generator_speed": analyse(simulation.speed_pu[window, 4], 240, poles=20),
            "electrical_torque": analyse(simulation.electrical_torque_pu[window], 240, poles=20),
            "terminal_voltage": analyse(simulation.voltage_pu[window], 240, poles=20),
        }
    (output / "results.json").write_text(json.dumps(result, indent=2, allow_nan=False) + "\n",
                                         encoding="utf-8")
    (output / "comparison.md").write_text(markdown_report(result), encoding="utf-8")
    return result


def markdown_report(result):
    lines = ["# SSR numerical report", "", "Generated by `scripts/run_ssr_benchmark.py`.", "",
             result["scope"], "", "Source: [IEEE FBM (1977)](https://doi.org/10.1109/T-PAS.1977.32485).",
             "See [MODEL.md](MODEL.md) and [SOURCES.md](SOURCES.md) for definitions and limits.", "",
             "## Shaft-only no-load comparison", "",
             "Decay values below are the configured published no-load inputs, recovered by the",
             "estimator. This validates estimation, not an electrical damping prediction.", "",
             "| Mode | Published Hz | Pencil Hz | Absolute error Hz | Error % | Published decay 1/s | Pencil decay 1/s | Decay error 1/s | Pencil amplitude pu | Welch Hz | Welch amplitude pu |",
             "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    shaft = result["shaft_no_load"]
    for pencil, spectral in zip(shaft["matrix_pencil"]["comparison"],
                                shaft["welch"]["comparison"]):
        estimate = pencil["estimate"]
        spectral_estimate = spectral["estimate"]
        spectral_hz = f'{spectral_estimate["frequency_hz"]:.6f}' if spectral_estimate else "missed"
        spectral_amp = f'{spectral_estimate["amplitude"]:.6g}' if spectral_estimate else "—"
        if estimate is None:
            lines.append(f'| {pencil["mode"]} | {pencil["published_frequency_hz"]} | missed |')
            continue
        lines.append(f'| {pencil["mode"]} | {pencil["published_frequency_hz"]:.2f} '
                     f'| {estimate["frequency_hz"]:.6f} '
                     f'| {pencil["absolute_frequency_error_hz"]:.6f} '
                     f'| {pencil["frequency_error_percent"]:.5f} '
                     f'| {pencil["published_decay_per_s"]:.3f} '
                     f'| {estimate["decay_per_s"]:.6f} '
                     f'| {pencil["absolute_decay_error_per_s"]:.3g} '
                     f'| {estimate["amplitude"]:.6g} | {spectral_hz} | {spectral_amp} |')
    lines += ["", "Welch decay and damping ratio: **unresolved for every mode**.",
              "Pencil amplitude is peak amplitude at window start; Welch amplitude is",
              "sqrt(2) times window-band RMS. No published amplitude reference is available.",
              "Complete damping ratios, Welch errors and undamped comparison are in `results.json`.",
              "", f'Computed fifth shaft mode: **{result["shaft_computed_frequencies_hz"][5]:.6f} Hz**;',
              "published fifth frequency/damping are **unverified**. Pencil detects the weak",
              "fifth shaft mode; the default Welch threshold misses it.", ""]
    if "fault" in result:
        lines += ["## Coupled balanced-fault experiment", "", result["fault"]["reference_warning"], "",
                  "The following differences are proximity to bare-shaft references, **not**",
                  "coupled-mode prediction errors. Ambiguous means multiple candidate poles.", "",
                  "| Signal | Mode | Pencil status | Pencil Hz | Decay 1/s | Amplitude pu | Welch status | Welch Hz | Welch amplitude pu |",
                  "|---|---:|---|---:|---:|---:|---|---:|---:|"]
        for signal in ["generator_speed", "electrical_torque", "terminal_voltage"]:
            for pencil, spectral in zip(result["fault"][signal]["matrix_pencil"]["comparison"],
                                        result["fault"][signal]["welch"]["comparison"]):
                def fields(estimate, include_decay):
                    if estimate is None:
                        return "— | — | —" if include_decay else "— | —"
                    values = [f'{estimate["frequency_hz"]:.5f}']
                    if include_decay:
                        values.append(f'{estimate["decay_per_s"]:.5f}')
                    values.append(f'{estimate["amplitude"]:.6g}')
                    return " | ".join(values)

                lines.append(f'| {signal} | {pencil["mode"]} | {pencil["status"]} '
                             f'| {fields(pencil["estimate"], True)} | {spectral["status"]} '
                             f'| {fields(spectral["estimate"], False)} |')
        lines += ["", "Negative decay is fitted growth. Fault damping is **not independently validated**.",
                  "All candidate and unmatched poles remain in `results.json`; no mode is silently removed.",
                  "", f'Maximum shaft speed deviation: **{result["fault"]["max_speed_deviation_pu"]:.6f} pu**.',
                  "This large excursion limits physical interpretation of the ideal elastic model.",
                  "", "Frozen-shaft electrical resonance (not a mechanical estimator output):", "",
                  f'- Intact circuit: {result["electrical_resonance"]["intact_frozen_shaft_hz"]:.5f} Hz.',
                  f'- Fault equivalent: {result["electrical_resonance"]["fault_thevenin_frozen_shaft_hz"]:.5f} Hz.',
                  "- Primary source describes approximately 40 Hz, not an exact numerical target.", ""]
    lines += ["## Execution record", "", f'Environment: `{json.dumps(result["environment"])}`.', "",
              "Hosted CI evidence is linked in the PR. Independent numerical review by Abhijith is pending.", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("artifacts/ssr"))
    parser.add_argument("--shaft-only", action="store_true")
    args = parser.parse_args()
    results = run(args.output, include_fault=not args.shaft_only)
    for section in ["shaft_no_load", "shaft_transient_undamped"]:
        for method in ["matrix_pencil", "welch"]:
            print(section, method, [(row["mode"], row["status"],
                                     row.get("absolute_frequency_error_hz"))
                                    for row in results[section][method]["comparison"]])
    print("Saved", args.output / "results.json")
